#!/usr/bin/env python
"""Regenerate the auto sections of reports/RESULTS.md + figures from saved predictions."""

from __future__ import annotations

import argparse
import datetime as dt

from receipt_vlm.eval.metrics import ScoreTable
from receipt_vlm.eval.report import (
    ModelRun,
    breakdown_table,
    compare,
    comparison_table,
    field_table,
    headline_table,
    metrics_payload,
    plot_field_heatmap,
    plot_latency_vs_f1,
    plot_overall,
    replace_auto_section,
)
from receipt_vlm.eval.runner import load_split, pred_path, score_predictions, select_subset
from receipt_vlm.prompts import PROMPT_VERSION
from receipt_vlm.utils.config import load_config
from receipt_vlm.utils.io import read_jsonl, resolve
from receipt_vlm.utils.logging import get_logger

log = get_logger("make_report")


def build_split(cfg: dict, split: str, out_md: str, fig_dir: str) -> None:  # type: ignore[type-arg]
    rep = cfg["report"]
    b, seed = int(cfg["bootstrap"]["resamples"]), int(cfg["seed"])
    try:
        samples = select_subset(
            load_split(cfg["data_dir"], split), cfg.get("subset", {}).get(split), seed
        )
    except FileNotFoundError as e:
        log.warning("%s", e)
        return
    ids = {s["id"] for s in samples}
    runs, not_run = [], {}
    for mid in rep.get("order", list(cfg["models"])):
        spec = cfg["models"][mid]
        p = pred_path(cfg["preds_dir"], mid, split, cfg.get("pred_tag", ""))
        preds = [r for r in read_jsonl(p) if r["id"] in ids] if p.exists() else []
        if len({r["id"] for r in preds}) < len(ids):
            not_run[mid] = (
                f"{spec.get('desc', '')} — no complete predictions for `{split}` ({len(preds)}/{len(ids)})"
            )
            continue
        scores = score_predictions(samples, preds)
        table = ScoreTable.from_scores(scores)
        runs.append(
            ModelRun(
                mid, spec.get("desc", ""), scores, table, metrics_payload(scores, table, b, seed)
            )
        )
    ours = set(rep.get("ours", []))
    by_id = {r.model_id: r for r in runs}
    comps = [
        compare(by_id[a], by_id[c], b, seed)
        for a, c in rep.get("comparisons", [])
        if a in by_id and c in by_id
    ]

    fig = resolve(fig_dir)
    fig.mkdir(parents=True, exist_ok=True)
    parts = [
        f"_Auto-generated by `make report` on {dt.date.today().isoformat()} from `{cfg['preds_dir']}`; "
        f"prompt `{PROMPT_VERSION}`, max_new_tokens={cfg['generation']['max_new_tokens']}, "
        f"image cap {cfg['image']['max_pixels']} px, greedy decoding; 95% percentile-bootstrap CIs "
        f"({b} resamples over images, seed {seed}). Do not edit by hand._",
        "",
        f"### Headline metrics ({split}, n = {len(samples)})",
        "",
        headline_table(runs, not_run),
        "",
    ]
    if runs:
        plot_overall(runs, ours, fig / f"{split}_overall_f1.png")
        plot_field_heatmap(runs, fig / f"{split}_field_f1.png")
        plot_latency_vs_f1(runs, ours, fig / f"{split}_latency_vs_f1.png")
        rel = "figures"
        parts += [
            f"![Overall F1 with 95% CI]({rel}/{split}_overall_f1.png)",
            "",
            "### Per-field F1 (strict), support = gold non-null instances",
            "",
            field_table(runs),
            "",
            f"![Per-field F1]({rel}/{split}_field_f1.png)",
            "",
            "### By language (overall F1)",
            "",
            breakdown_table(runs, "language"),
            "",
            "### By source (overall F1)",
            "",
            breakdown_table(runs, "source"),
            "",
            f"![Latency vs F1]({rel}/{split}_latency_vs_f1.png)",
            "",
        ]
    if comps:
        parts += [
            "### Paired comparisons (paired bootstrap over images; McNemar on total exact match)",
            "",
            comparison_table(comps),
            "",
        ]
    elif rep.get("comparisons"):
        parts += [
            "_No comparison could be computed: at least one model of every configured pair has no predictions yet._",
            "",
        ]
    replace_auto_section(
        resolve(out_md), split, "\n".join(parts), f"Results on `{split}` (auto-generated)"
    )
    log.info("%s: %d models reported, %d not run", split, len(runs), len(not_run))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default="configs/eval/final.yaml")
    ap.add_argument("--out", default="reports/RESULTS.md")
    ap.add_argument("--fig-dir", default="reports/figures")
    ap.add_argument("overrides", nargs="*")
    args = ap.parse_args()
    cfg = load_config(args.config, args.overrides)
    for split in cfg["report"]["splits"]:
        build_split(cfg, split, args.out, args.fig_dir)


if __name__ == "__main__":
    main()
